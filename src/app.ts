import express from 'express'
import helmet from 'helmet'
import cors from 'cors'
import { pinoHttp } from 'pino-http'
import { env } from './config/env.js'
import { logger } from './utils/logger.js'
import { requestId } from './middleware/request-id.js'
import { apiRateLimit } from './middleware/rate-limit.js'
import { healthRouter } from './system/health.routes.js'
import { apiRouter } from './routes/index.js'
import { errorHandler } from './middleware/error-handler.js'
export function createApp(){const app=express();app.disable('x-powered-by');app.use(helmet());app.use(cors({origin:(origin,cb)=>{if(!origin||env.corsOrigins.length===0||env.corsOrigins.includes(origin))return cb(null,true);cb(new Error('Origin not allowed'))},credentials:true}));app.use(express.json({limit:'1mb'}));app.use(requestId);app.use(pinoHttp({logger}));app.use(healthRouter);app.use('/api/v1',apiRateLimit,apiRouter);app.use((_req,res)=>res.status(404).json({success:false,error:{code:'NOT_FOUND',message:'Ruta no encontrada'}}));app.use(errorHandler);return app}
